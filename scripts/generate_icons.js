// Generates minimal valid PNG and ICO files for Tauri build
import fs from "fs";
import path from "path";

const iconsDir = path.resolve("src-tauri", "icons");
if (!fs.existsSync(iconsDir)) {
  fs.mkdirSync(iconsDir, { recursive: true });
}

// 1x1 transparent/indigo PNG buffer
const minimalPng = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
  0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x20,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x73, 0x7a, 0x7a, 0xf4, 0x00, 0x00, 0x00,
  0x1b, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x60, 0x18, 0x05, 0xa3,
  0x60, 0x14, 0x8c, 0x82, 0x51, 0x30, 0x28, 0x18, 0x05, 0xa3, 0x60, 0x14,
  0x8c, 0x82, 0x51, 0x30, 0x00, 0x00, 0x1d, 0x20, 0x04, 0x81, 0x3e, 0xb6,
  0x6e, 0x01, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42,
  0x60, 0x82
]);

// Minimal 1-image ICO header + PNG image
const icoHeader = Buffer.from([
  0x00, 0x00,             // Reserved
  0x01, 0x00,             // Type 1 = ICO
  0x01, 0x00,             // 1 Image
  0x20,                   // Width 32
  0x20,                   // Height 32
  0x00,                   // Color palette
  0x00,                   // Reserved
  0x01, 0x00,             // Color planes
  0x20, 0x00,             // 32 bpp
  ...minimalPng.length.toString(16).padStart(8, '0').match(/../g).reverse().map(h => parseInt(h, 16)), // Size of image data
  0x16, 0x00, 0x00, 0x00  // Offset of image data (22 bytes)
]);

const icoFile = Buffer.concat([icoHeader, minimalPng]);

fs.writeFileSync(path.join(iconsDir, "32x32.png"), minimalPng);
fs.writeFileSync(path.join(iconsDir, "128x128.png"), minimalPng);
fs.writeFileSync(path.join(iconsDir, "icon.png"), minimalPng);
fs.writeFileSync(path.join(iconsDir, "icon.ico"), icoFile);

console.log("Icons generated successfully in src-tauri/icons/");
